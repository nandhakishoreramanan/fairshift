  const DICTS = { en, hi, ta, te, bn };
  const SPEECH = { en: 'en-IN', hi: 'hi-IN', ta: 'ta-IN', te: 'te-IN', bn: 'bn-IN' };
  const NATIVE = { en: 'English', hi: 'हिन्दी', ta: 'தமிழ்', te: 'తెలుగు', bn: 'বাংলা' };

  let current = localStorage.getItem('fs_lang') || 'en';

  function t(key, params) {
    const dict = DICTS[current] || en;
    let s = dict[key] || en[key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  }

  function setLang(lang) {
    if (!DICTS[lang]) return;
    current = lang;
    localStorage.setItem('fs_lang', lang);
    document.documentElement.lang = lang;
  }

  /** Fill every element carrying data-i18n="key". */
  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
  }

  document.documentElement.lang = current;
  window.I18N = { t, setLang, apply, get lang() { return current; }, LANGS: Object.keys(DICTS), SPEECH, NATIVE };
